close all;



%% 1. Create and process the mesh

% Structured domain: 1000 x 1000 x 100.
% grid = structuredMesh(11, 11, 7, ...
%                       [0 1000], [0 1000], [0 100]);

% Alternative: refine the central region using the internal mesh generator.
% grid = structuredMesh([4 7 4], [4 7 4], [3 5 3], ...
%                       [0 400 600 1000], ...
%                       [0 400 600 1000], ...
%                       [0 40 60 100]);

% Alternative: import an existing mesh.
grid = Grid();
grid.importMesh('domain.vtk');

% Compute the geometric quantities required by the discretization,
% including cell volumes and cell/surface centers.
grid.processGeometry();


%% 2. Define fluid and rock properties

% Materials can be defined programmatically or read from an XML file.
materials = Materials();

materials.addFluid( ...
    'dynamicViscosity', 1.1574e-11, ...
    'specificWeight',   0.0, ...
    'compressibility',  4.4e-7);

% Associate the sand material with cells carrying tag 1.
materials.addSolid('name', "sand", 'cellTags', 1);

materials.addPorousRock("sand", ...
    'permeability',    1e-12, ...
    'porosity',        0.375, ...
    'compressibility', 1e-5);

% Alternative: load the material definitions from a file.
% materials = Materials('materials.xml');


%% 3. Define flow boundary conditions

bc = Boundaries(grid);

% Prescribe zero pressure on the top boundary (z = 100).
topSurfId = find(grid.surfaces.center(:, 3) > 99.99);

bc.addBC( ...
    'name',           "topPressure", ...
    'type',           "dirichlet", ...
    'field',          "surface", ...
    'entityListType', "bcList", ...
    'entityList',     topSurfId, ...
    'variable',       "pressure");

% Boundary-condition events define the prescribed values in time.
% Here, the top pressure is zero from the beginning of the simulation.
bc.addBCEvent("topPressure", 'time', 0.0, 'value', 0.0);

% Select the cell near the center of the domain for an extraction well.
wellCellsId = find( ...
    grid.cells.center(:, 1) > 490.0 & ...
    grid.cells.center(:, 1) < 510.0 & ...
    grid.cells.center(:, 2) > 490.0 & ...
    grid.cells.center(:, 2) < 510.0 & ...
    grid.cells.center(:, 3) > 48.0 & ...
    grid.cells.center(:, 3) < 51.0);

bc.addBC( ...
    'name',           "extractionWell", ...
    'type',           "source", ...
    'field',          "cell", ...
    'entityListType', "bcList", ...
    'entityList',     wellCellsId, ...
    'variable',       "pressure");

% A cell source is specified per unit volume and has units of 1/time.
% Divide the total extraction rate by the selected cell volume.
% The negative sign denotes extraction.
wellRate   = -1e4;  % Volume/time; e.g., m^3/year if time is measured in years.
wellVolume = sum(grid.cells.volume(wellCellsId));
wellSource = wellRate / wellVolume;

bc.addBCEvent("extractionWell", 'time', 0.0, 'value', wellSource);


%% 4. Configure and solve homogeneous single-phase flow

% Combine the mesh, materials, and boundary conditions into a domain,
% then select the finite-volume TPFA flow solver.
domain = Discretizer( ...
    'Boundaries', bc, ...
    'Materials',  materials, ...
    'Grid',       grid);

domain.addPhysicsSolver("SinglePhaseFlowFVTPFA");

% Use a constant time step over the interval [0, 10].
input = struct( ...
    'Start',           0.0, ...
    'End',             10.0, ...
    'DtInit',          5e-1, ...
    'DtMax',           5e-1, ...
    'DtMin',           5e-1, ...
    'incrementFactor', 1.0);

simParam = SimulationParameters(input);

% Define the requested output times and the output file prefix.
outputTimes = [0 0.5 1:10];
out = OutState( ...
    'printTimes',  outputTimes, ...
    'outputFile', fullfile('Output', 'flow'), ...
    'matFileName', fullfile('Output', 'flow'));

solver = NonLinearImplicit( ...
    'simulationparameters', simParam, ...
    'domains',              domain, ...
    'output',               out);

solver.simulationLoop();


%% 5. Add a clay layer and initialize hydrostatic pressure

% Assign tag 2 to cells in the bottom layer (z < 30).
% The remaining cells retain the sand material.
bottomLayerId = find(grid.cells.center(:, 3) < 30.0);
grid.cells.tag(bottomLayerId) = 2;

materials.addSolid('name', "clay", 'cellTags', 2);

materials.addPorousRock("clay", ...
    'permeability',    1e-16, ...
    'porosity',        0.3, ...
    'compressibility', 1e-5);

% Rebuild the domain to include the updated material assignments.
domain = Discretizer( ...
    'Boundaries', bc, ...
    'Materials',  materials, ...
    'Grid',       grid);

domain.addPhysicsSolver("SinglePhaseFlowFVTPFA", 'steadyState', 0);

% Hydrostatic pressure: p(z) = gamma * (100 - z).
% This gives zero pressure at the top and increasing pressure with depth.
% gamma = materials.getFluid.getSpecificWeight;
% hydrostaticPressure = gamma * (100 - grid.cells.center(:, 3));
%domain.setState(hydrostaticPressure, "pressure");

out = OutState( ...
    'printTimes',  outputTimes, ...
    'outputFile', fullfile('Output', 'flowClay'), ...
    'matFileName', fullfile('Output', 'flowClay'));

solver = NonLinearImplicit( ...
    'simulationparameters', simParam, ...
    'domains',              domain, ...
    'output',               out);

solver.simulationLoop();


%% 6. One-way coupling: use flow results to drive mechanics

% Add linear elastic constitutive laws to both rock materials.
materials.addConstitutiveLaw("sand", "Elastic", ...
    'youngModulus', 1e4, ...
    'poissonRatio', 0.25);

materials.addConstitutiveLaw("clay", "Elastic", ...
    'youngModulus', 0.5e4, ...
    'poissonRatio', 0.25);

% Constrain all displacement components of all nodes on the bottom boundary.
nodesBottom = find(grid.coordinates(:,3) < 1e-3);
bc.addBC( ...
    'name',           "fixBottom", ...
    'type',           "dirichlet", ...
    'field',          "node", ...
    'entityListType', "bclist", ...
    'entityList',     nodesBottom, ...
    'variable',       "displacements", ...
    'components',     ["x", "y", "z"]);

bc.addBCEvent("fixBottom", 'time', 0.0, 'value', 0.0);

% Pass the previously computed pressure changes to the mechanical model
% through a dedicated volume-force boundary condition.
bc.addBC( ...
    'name',           "pressureChange", ...
    'type',           "volumeForce", ...
    'field',          "cell", ...
    'entityListType', "bcList", ...
    'entityList',     1:grid.cells.num, ...
    'variable',       "displacements");

flowModel = load(fullfile('Output', 'flowClay.mat'));
time     = [flowModel.output.time];
pressure = [flowModel.output.pressure];

% Apply pressure changes relative to the first saved flow state.
deltaPressure = pressure - pressure(:, 1);

for i = 1:numel(time)
    bc.addBCEvent("pressureChange", ...
        'time',  time(i), ...
        'value', deltaPressure(:, i));
end

domain = Discretizer( ...
    'Boundaries', bc, ...
    'Materials',  materials, ...
    'Grid',       grid);

domain.addPhysicsSolver("Poromechanics");

out = OutState( ...
    'printTimes',  0:10, ...
    'outputFile', fullfile('Output', 'coupledProblemOneWay'), ...
    'matFileName', fullfile('Output', 'coupledProblemOneWay'));

solver = NonLinearImplicit( ...
    'simulationparameters', simParam, ...
    'domains',              domain, ...
    'output',               out);

solver.simulationLoop();


%% 7. Fully coupled poromechanics

% Remove the prescribed pressure-change load: the coupled model now
% computes pressure and displacement together.
bc.removeBC("pressureChange");

domain = Discretizer( ...
    'Boundaries', bc, ...
    'Materials',  materials, ...
    'Grid',       grid);

domain.addPhysicsSolver("BiotFullyCoupled");

% Optional: start from the hydrostatic pressure distribution.
% domain.setState(hydrostaticPressure, "pressure");

out = OutState( ...
    'printTimes',  [0 0.1 0.25 0.5 1:3], ...
    'outputFile', fullfile('Output', 'coupledProblemFC'), ...
    'matFileName', fullfile('Output', 'coupledProblemFC'));

solver = NonLinearImplicit( ...
    'simulationparameters', simParam, ...
    'domains',              domain, ...
    'output',               out);

solver.simulationLoop();


%% 8. Poromechanics with a fixed-stress split

% Solve the coupled problem by iterating between flow and mechanics
% within each time step.
domain = Discretizer( ...
    'Boundaries', bc, ...
    'Materials',  materials, ...
    'Grid',       grid);

domain.addPhysicsSolver("BiotFixedStressSplit");

% Optional: use the same hydrostatic initialization as above.
% domain.setState(hydrostaticPressure, "pressure");

out = OutState( ...
    'printTimes',  [0 0.1 0.25 0.5 1:3], ...
    'outputFile', fullfile('Output', 'coupledProblemFS'), ...
    'matFileName', fullfile('Output', 'coupledProblemFS'));

% Set the relative convergence tolerance for the split iterations.
solver = FixedStressSplit( ...
    'simulationparameters', simParam, ...
    'domains',              domain, ...
    'output',               out, ...
    'reltolerance',         2e-2);

solver.simulationLoop();